def rebrand_text(name: str, inner: str) -> str:
    if name in FIXED_VALUES:
        return FIXED_VALUES[name]
    brand = ORG if name in ORG_KEYS else APP
    parts = TAG_SPLIT_RE.split(inner)
    for i in range(0, len(parts), 2):  # text segments only, never inside tags
        if LINK_RE.search(parts[i]):
            raise RebrandError(f"string {name}: contains a Nextcloud link or address; add a FIXED_VALUES entry")
        # Case-insensitive: some languages inflect the name in lower case (hu "nextcloudos").
        parts[i] = NAME_RE.sub(brand, parts[i])
    new = "".join(parts)
    if BRAND_RE.search(TAG_SPLIT_RE.sub("", new)):
        raise RebrandError(f"string {name}: unhandled spelling left after rewrite: {new!r}")
    return new


def string_files() -> dict[str, str]:
    owned = {name for _, items in SETUP for _, name, _ in items}
    out: dict[str, str] = {}
    res = ROOT / MAIN_RES
    for vdir in sorted(p for p in res.iterdir() if p.is_dir() and p.name.startswith("values")):
        src = f"{MAIN_RES}/{vdir.name}/strings.xml"
        if not (ROOT / src).is_file():
            continue
        raw = read(src)
        text = COMMENT_RE.sub("", raw)
        root_tag = re.search(r"<resources\b[^>]*>", text)
        if not root_tag:
            raise RebrandError(f"{src}: no <resources> element")
        elements = []
        for m in STRING_ELEMENT_RE.finditer(text):
            tag, attrs, inner = m.group(1), m.group(2), m.group(4) or ""
            name_m = re.search(r'\bname="([^"]+)"', attrs)
            if not name_m:
                continue
            name = name_m.group(1)
            if name in owned:
                continue
            if not (BRAND_RE.search(inner) or name in ALWAYS_OVERRIDE):
                continue
            new_inner = rebrand_text(name, inner) if tag == "string" else re.sub(
                r"(<item\b[^>]*>)(.*?)(</item>)", lambda im: im.group(1) + rebrand_text(name, im.group(2)) + im.group(3),
                inner, flags=re.S)
            if tag == "string" and name not in FIXED_VALUES:
                if Counter(FORMAT_RE.findall(inner)) != Counter(FORMAT_RE.findall(new_inner)):
                    raise RebrandError(f"{src} {name}: format specifiers changed")
            elements.append(f"    <{tag}{attrs}>{new_inner}</{tag}>")
        if not elements:
            continue
        upstream_values = f"{MAIN_RES}/values/strings.xml"
        holders, licence = upstream_spdx(read(upstream_values))
        root_open = re.sub(r"\s+", " ", root_tag.group(0)).replace(" >", ">")
        body = root_open + "\n" + "\n".join(elements) + "\n</resources>"
        content = xml_file(body, source=src, upstream_spdx=holders, licence=licence)
        try:
            ET.fromstring(content.encode("utf-8"))
        except ET.ParseError as e:
            raise RebrandError(f"generated strings for {vdir.name} are not valid XML: {e}") from e
        out[f"{ND_RES}/{vdir.name}/strings.xml"] = content
    return out


