def version_code() -> int:
    nums = dict(UPSTREAM_VERSION_CODE_RE.findall(read("app/build.gradle.kts")))
    if len(nums) != 4:
        raise RebrandError("app/build.gradle.kts: versionMajor/Minor/Patch/Build not found")
    v = {k: int(x) for k, x in nums.items()}
    return (v["versionMajor"] * 10000000 + v["versionMinor"] * 10000 + v["versionPatch"] * 100 + v["versionBuild"]
            + NOURAX_REVISION - 1)


def fastlane_files() -> dict[str, str]:
    out = {}
    code = version_code()
    for locale, t in STORE.items():
        base = f"{FASTLANE}/{locale}"
        if len(t["short"]) > 80:
            raise RebrandError(f"short description for {locale} is longer than 80 characters")
        out[f"{base}/title.txt"] = t["title"] + "\n"
        out[f"{base}/short_description.txt"] = t["short"] + "\n"
        out[f"{base}/full_description.txt"] = t["full"] + "\n"
        out[f"{base}/changelogs/{code}.txt"] = t["changelog"] + "\n"
    return out


