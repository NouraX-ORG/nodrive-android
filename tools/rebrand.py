def read(rel: str) -> str:
    path = ROOT / rel
    if not path.is_file():
        raise RebrandError(f"missing upstream file {rel}")
    return path.read_text(encoding="utf-8")


def xml_header(source: str | None = None, upstream_spdx: list[str] | None = None,
               licence: str | None = "AGPL-3.0-or-later") -> str:
    lines = ["<!--", f"  ~ {APP} by {ORG}: generated by tools/rebrand.py, do not edit by hand."]
    if source:
        lines.append(f"  ~ Derived from {source}")
    lines.append("  ~")
    lines += [f"  ~ SPDX-FileCopyrightText: {c}" for c in (upstream_spdx or [])]
    lines.append("  ~ SPDX-FileCopyrightText: 2026 Nourax")
    if licence:  # None: the body keeps the upstream header with its own licence line
        lines.append(f"  ~ SPDX-License-Identifier: {licence}")
    lines.append("-->")
    return "\n".join(lines) + "\n"


def upstream_spdx(text: str) -> tuple[list[str], str]:
    holders = re.findall(r"SPDX-FileCopyrightText:\s*(.+?)\s*$", text, re.M)
    licence = re.search(r"SPDX-License-Identifier:\s*(.+?)\s*$", text, re.M)
    return holders, (licence.group(1) if licence else "AGPL-3.0-or-later OR GPL-2.0-only")


def xml_file(body: str, **header) -> str:
    return '<?xml version="1.0" encoding="utf-8"?>\n' + xml_header(**header) + body.strip("\n") + "\n"


def escape_android(text: str) -> str:
    """Plain text -> Android string resource value."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")


