def planned_changes() -> tuple[dict[str, str], list[str]]:
    """Return {path: new content} for every file that differs, and stale files to delete."""
    files = generated_files()
    files["app/build.gradle.kts"] = patch_gradle(read("app/build.gradle.kts"))
    for rel, hooks in HOOKS.items():
        files[rel] = patch_hooks(rel, hooks, read(rel))
    changed = {}
    for rel, content in files.items():
        path = ROOT / rel
        current = path.read_bytes().decode("utf-8") if path.is_file() else None
        if current != content:
            changed[rel] = content
    stale = []
    for p in sorted([*(ROOT / ND_RES).glob("values*/strings.xml"), *(ROOT / ND_RES).glob(f"values*/{LIBRARY_FILE}")]):
        rel = p.relative_to(ROOT).as_posix()
        if rel not in files:
            stale.append(rel)
    return changed, stale


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if a run would change anything")
    ap.add_argument("--import-library-strings", metavar="RESOURCES_TXT", type=Path,
                    help=f"update {LIBRARY_STRINGS} from an 'aapt2 dump resources' file, then exit")
    args = ap.parse_args()
    if args.import_library_strings:
        try:
            return import_library_strings(args.import_library_strings)
        except RebrandError as e:
            print(f"rebrand: ERROR: {e}")
            return 2
    try:
        changed, stale = planned_changes()
    except RebrandError as e:
        print(f"rebrand: ERROR: {e}")
        return 2
    if args.check:
        for rel in changed:
            print(f"rebrand --check: would change {rel}")
        for rel in stale:
            print(f"rebrand --check: would delete stale {rel}")
        n = len(changed) + len(stale)
        print(f"rebrand --check: {n} file(s) out of date" if n else "rebrand --check: up to date")
        return 1 if n else 0
    for rel, content in changed.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        print(f"rebrand: wrote {rel}")
    for rel in stale:
        (ROOT / rel).unlink()
        print(f"rebrand: deleted stale {rel}")
    print(f"rebrand: {len(changed)} file(s) written, {len(stale)} deleted" if changed or stale
          else "rebrand: nothing to do")
    return 0


if __name__ == "__main__":
    sys.exit(main())
