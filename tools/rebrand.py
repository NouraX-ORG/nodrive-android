def manifest() -> str:
    src = f"{MAIN}/AndroidManifest.xml"
    main_root = ET.fromstring(read(src).encode("utf-8"))
    app = main_root.find("application")
    fda = next((a for a in app.findall("activity") if a.get(A + "name") == ".ui.activity.FileDisplayActivity"), None)
    if fda is None:
        raise RebrandError(f"{src}: FileDisplayActivity not found")
    if not any(a.get(A + "name") == ".authentication.DeepLinkLoginActivity" for a in app.findall("activity")):
        raise RebrandError(f"{src}: DeepLinkLoginActivity not found")
    act = copy.deepcopy(fda)
    act.set(A + "name", "com.owncloud.android.ui.activity.FileDisplayActivity")
    act.set(T + "node", "replace")
    https_filters = 0
    for f in list(act.findall("intent-filter")):
        actions = {a.get(A + "name") for a in f.findall("action")}
        schemes = {d.get(A + "scheme") for d in f.findall("data") if d.get(A + "scheme")}
        if "com.nextcloud.intent.OPEN_ECOSYSTEM_APP" in actions or "http" in schemes:
            act.remove(f)
            continue
        if "https" in schemes:
            https_filters += 1
            # Not an App Link yet (no assetlinks.json on the server); saying so explicitly also keeps
            # lint's "App Link format but missing autoVerify" error away.
            f.set(A + "autoVerify", "false")
            for d in f.findall("data"):
                if d.get(A + "host") is not None:
                    d.set(A + "host", HOST)
    if https_filters == 0:
        raise RebrandError(f"{src}: no https link filters on FileDisplayActivity any more")

    root = ET.Element("manifest")
    root.append(ET.Comment(" No self-updater, so no permission to install packages (as in upstream's gplay). "))
    root.append(ET.Element("uses-permission", {A + "name": "android.permission.REQUEST_INSTALL_PACKAGES",
                                               T + "node": "remove"}))
