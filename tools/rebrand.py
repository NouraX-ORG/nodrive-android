def main_resource_attrs(main_text: str, rtype: str, name: str, where: str) -> str:
    m = re.search(rf'<{rtype}\s+name="{re.escape(name)}"([^>]*?)/?>', main_text)
    if not m:
        raise RebrandError(f"{where}: <{rtype} name=\"{name}\"> not found upstream (renamed?)")
    return m.group(1).rstrip()


def setup_xml() -> str:
    src = f"{MAIN_RES}/values/setup.xml"
    main_text = read(src)
    body = ["<resources>"]
    for title, items in SETUP:
        body.append(f"    <!-- {title} -->")
        for rtype, name, value in items:
            attrs = main_resource_attrs(main_text, rtype, name, src)
            body.append(f'    <{rtype} name="{name}"{attrs}>{value}</{rtype}>')
        body.append("")
    body[-1] = "</resources>"
    holders, licence = upstream_spdx(main_text)
    return xml_file("\n".join(body), source=src, upstream_spdx=holders, licence=licence)


def values_override(src: str, items: list[tuple[str, str, str]], comment: str) -> str:
    main_text = read(src)
    body = ["<resources>", f"    <!-- {comment} -->"]
    for rtype, name, value in items:
        attrs = main_resource_attrs(main_text, rtype, name, src)
        body.append(f'    <{rtype} name="{name}"{attrs}>{value}</{rtype}>')
    body.append("</resources>")
    holders, licence = upstream_spdx(main_text)
    return xml_file("\n".join(body), source=src, upstream_spdx=holders, licence=licence)


