def patch_gradle(text: str) -> str:
    stripped = MARKED_BLOCK_RE.sub("", text)
    if "register(\"generic\")" not in stripped or "val versionBuild" not in stripped:
        raise RebrandError("app/build.gradle.kts: upstream flavours or version variables not found")
