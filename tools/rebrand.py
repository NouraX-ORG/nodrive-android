def exposed_filepaths() -> str:
    src = f"{MAIN_RES}/xml/exposed_filepaths.xml"
    text = read(src)
    old = '<files-path name="user_files_internal" path="nextcloud/"/>'
    if text.count(old) != 1:
        raise RebrandError(f"{src}: user_files_internal path entry changed upstream")
    new = text.replace(old, '<files-path name="user_files_internal" path="nodrive/"/>')
    new = re.sub(r"^<\?xml[^>]*\?>\s*", "", new)
    return xml_file(new, source=src + " (data folder nodrive/)", licence=None)


def manifest() -> str:
    src = f"{MAIN}/AndroidManifest.xml"
    main_root = ET.fromstring(read(src).encode("utf-8"))
    app = main_root.find("application")
    fda = next((a for a in app.findall("activity") if a.get(A + "name") == ".ui.activity.FileDisplayActivity"), None)
    if fda is None:
        raise RebrandError(f"{src}: FileDisplayActivity not found")
    if not any(a.get(A + "name") == ".authentication.DeepLinkLoginActivity" for a in app.findall("activity")):
        raise RebrandError(f"{src}: DeepLinkLoginActivity not found")
    act = copy.deepcopy(fda)
    act.set(A + "name", "com.owncloud.android.ui.activity.FileDisplayActivity")
    act.set(T + "node", "replace")
    https_filters = 0
    for f in list(act.findall("intent-filter")):
        actions = {a.get(A + "name") for a in f.findall("action")}
        schemes = {d.get(A + "scheme") for d in f.findall("data") if d.get(A + "scheme")}
        if "com.nextcloud.intent.OPEN_ECOSYSTEM_APP" in actions or "http" in schemes:
            act.remove(f)
            continue
        if "https" in schemes:
            https_filters += 1
            f.attrib.pop(A + "autoVerify", None)
            for d in f.findall("data"):
                if d.get(A + "host") is not None:
                    d.set(A + "host", HOST)
    if https_filters == 0:
        raise RebrandError(f"{src}: no https link filters on FileDisplayActivity any more")

    root = ET.Element("manifest")
    root.append(ET.Comment(" No self-updater, so no permission to install packages (as in upstream's gplay). "))
    root.append(ET.Element("uses-permission", {A + "name": "android.permission.REQUEST_INSTALL_PACKAGES",
                                               T + "node": "remove"}))
    application = ET.SubElement(root, "application")
    application.append(ET.Comment(" Login links (nodrive://login/...) could add another server: NoDrive signs in "
                                  "only through Login Flow v2 at " + HOST + ". "))
    application.append(ET.Element("activity", {
        A + "name": "com.owncloud.android.authentication.DeepLinkLoginActivity", T + "node": "remove"}))
    application.append(ET.Comment(f" Generated from {src}: only https links to {HOST} (no autoVerify until "
                                  "assetlinks.json exists), no Nextcloud ecosystem action. "))
    application.append(act)
    ET.indent(root, space="    ")
    body = ET.tostring(root, encoding="unicode")
    body = body.replace(f'<manifest xmlns:android="{ANDROID_NS}" xmlns:tools="{TOOLS_NS}">',
                        f'<manifest xmlns:android="{ANDROID_NS}"\n    xmlns:tools="{TOOLS_NS}">', 1)
    holders, licence = upstream_spdx(read(src))
    return xml_file(body, source=src, upstream_spdx=holders, licence=licence)


