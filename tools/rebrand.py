def glyph_swap(target: str, glyph: str) -> str:
    tsrc, gsrc = f"{MAIN_RES}/drawable/{target}", f"{MAIN_RES}/drawable/{glyph}"
    t = ET.fromstring(read(tsrc).encode("utf-8"))
    g = ET.fromstring(read(gsrc).encode("utf-8"))
    if t.tag != "vector" or g.tag != "vector":
        raise RebrandError(f"{tsrc} or {gsrc} is no longer a <vector>")
    fill = next((p.get(A + "fillColor") for p in t.iter("path") if p.get(A + "fillColor")), "#FFFFFFFF")
    attrs = [f'android:width="{t.get(A + "width")}"', f'android:height="{t.get(A + "height")}"']
    for key in ("tint", "autoMirrored"):
        if t.get(A + key) is not None:
            attrs.append(f'android:{key}="{t.get(A + key)}"')
    attrs += [f'android:viewportWidth="{g.get(A + "viewportWidth")}"',
              f'android:viewportHeight="{g.get(A + "viewportHeight")}"']
    paths = []
    for p in g.iter("path"):
        extra = f' android:fillType="{p.get(A + "fillType")}"' if p.get(A + "fillType") else ""
        paths.append(f'    <path\n        android:fillColor="{fill}"{extra}\n'
                     f'        android:pathData="{p.get(A + "pathData")}" />')
    body = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    '
            + "\n    ".join(attrs) + ">\n" + "\n".join(paths) + "\n</vector>")
    gh, gl = upstream_spdx(read(gsrc))
    return xml_file(body, source=f"{gsrc} (neutral glyph in the frame of {target})", upstream_spdx=gh, licence=gl)


